w("| Largest narrowing | 2013 | 2025 | Change |"); w("|---|---|---|---|")
for _, x in s.sort_values("ch_harm").head(5).iterrows(): w(f"| {x.area_title} | {x.g0:.4f} | {x.g1:.4f} | {x.ch_harm:+.4f} |")
w("\n| Smallest narrowing | 2013 | 2025 | Change | Verdict |"); w("|---|---|---|---|---|")
for _, x in s.sort_values("ch_harm", ascending=False).head(5).iterrows(): w(f"| {x.area_title} | {x.g0:.4f} | {x.g1:.4f} | {x.ch_harm:+.4f} | {x.verdict} |")

