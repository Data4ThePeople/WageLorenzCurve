# ---------------------------------------------------------------- 7. major groups
w("## 7. Which groups take more of the wages than their share of jobs (U.S., May 2025)\n")
d = usable(RAW[2025][RAW[2025].area_type == 1]).assign(major=lambda x: x.occ_code.str[:2])
d["wages"] = d.tot_emp * d.a_mean
maj = RAW[2025][RAW[2025].o_group == "major"].drop_duplicates("occ_code").set_index(RAW[2025][RAW[2025].o_group == "major"].drop_duplicates("occ_code").occ_code.str[:2]).occ_title
gsum = d.groupby("major")[["tot_emp", "wages"]].sum(); gsum = gsum.assign(js=gsum.tot_emp / gsum.tot_emp.sum(), ws=gsum.wages / gsum.wages.sum())
gsum["ratio"] = gsum.ws / gsum.js
w("| Major group | Share of jobs | Share of wages | Wages per job vs. average |"); w("|---|---|---|---|")
for m, x in gsum.sort_values("ratio", ascending=False).iterrows():
    w(f"| {maj[m]} | {pct(x.js)} | {pct(x.ws)} | {(x.ratio-1)*100:+.0f}% |")

# ---------------------------------------------------------------- 8. BEA: what the curve can't see
w("\n## 8. What the curve can't see (BEA personal income by source, 2013 to 2024)\n")
b = inc[inc.complete].copy(); b["not_on"] = 1 - b.wages / b.personal_income; b["dir"] = b.dividends_interest_rent / b.personal_income
bw = b.pivot_table(index="area", columns="year", values=["not_on", "dir"])
usb = bw.loc["99"]
w(f"U.S.: not on the curve {pct(usb[('not_on', 2013)])} (2013) to {pct(usb[('not_on', 2024)])} (2024); "
  f"dividends, interest and rent {pct(usb[('dir', 2013)])} to {pct(usb[('dir', 2024)])}.")
for t, lab in ((2, "states"), (4, "metros")):
    ks = [k for k in m25.index[m25.area_type == t] if k in bw.index and not np.isnan(bw.loc[k, ('not_on', 2013)])]
    x = bw.loc[ks]
    grew = (x[('not_on', 2024)] > x[('not_on', 2013)]).sum(); dg = (x[('dir', 2024)] > x[('dir', 2013)]).sum()
    w(f"- {lab} ({len(ks)} with both years): not-on-the-curve share grew in {grew}, shrank in {len(ks)-grew}; "
      f"dividends, interest and rent share rose in {dg} of {len(ks)}.")
w("Limit: shows where income comes from, not who receives it; capital gains are not in personal income.\n")

# ---------------------------------------------------------------- 9. bottom half
