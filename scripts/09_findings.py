bh = pd.DataFrame(rows, columns=["area", "bottom_half", "top10"]).sort_values("bottom_half")
w("| Metro | Lowest-paid half's share | Top-paid 10%'s share |"); w("|---|---|---|")
for _, x in bh.head(6).iterrows(): w(f"| {x.area} | {pct(x.bottom_half)} | {pct(x.top10)} |")
